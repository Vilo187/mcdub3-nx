/**
 * Midnight Club 3: DUB Edition (Xbox) -- recompiled game entry point
 *
 * Boot order (xboxrecomp's, the same on every host):
 *   crash reporter -> load default.xbe -> xbox_MemoryLayoutInit ->
 *   devices (APU, USB pads, renderer) -> xbox_kernel_init -> xbox_path_init ->
 *   xbox_kernel_bridge_init -> g_esp = XBOX_STACK_TOP ->
 *   recomp_dispatch_init -> xbe_entry_point()
 *
 * Game data is the extracted disc (default.xbe + data), never the ISO:
 *   Linux:  $MC3_GAME_DIR, else ./game
 *   Switch: sdmc:/switch/<MC3_APP>/game
 */

