#!/usr/bin/env bash
# First contact with the disc: parse the XBE, record what the port needs from
# it, then run the full lift.
#
#   tools/first_lift.sh
#
# Writes:
#   $MC3_ANALYSIS_DIR/xbe_summary.txt   parser report (sections, kernel
#                                        imports, entry point, XDK version)
#   config/<game>/xbe_facts.h            entry point + title ID for main.c;
#                                        committed (addresses, not game data);
#                                        MC3_FACTS_H=<file> writes elsewhere
#                                        (tests on other XBEs)
# then runs tools/regen.sh.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/env.sh"
mc3_python

mc3_need_game
mkdir -p "$MC3_ANALYSIS_DIR"
XBE_JSON="${MC3_XBE%.xbe}_analysis.json"

cd "$XBOXRECOMP_DIR"
"$MC3_PYTHON" -m tools.xbe_parser "$MC3_XBE" --json "$XBE_JSON" | tee "$MC3_ANALYSIS_DIR/xbe_summary.txt"

"$MC3_PYTHON" - "$XBE_JSON" "$MC3_FACTS_H" "$MC3_XBE" "${MC3_EDITION:-}" <<'EOF'
import json, struct, sys
src, dst, xbe, edition = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4]
d = json.load(open(src))
raw = open(xbe, "rb").read()
# The certificate: game region (+0xA0) and version (+0xAC). The edition
# names the NRO (mcdub3-nx-<edition>.nro); MC3_EDITION overrides it.
base, = struct.unpack_from("<I", raw, 0x104)
cert, = struct.unpack_from("<I", raw, 0x118)
region, = struct.unpack_from("<I", raw, cert - base + 0xA0)
version, = struct.unpack_from("<I", raw, cert - base + 0xAC)
if not edition:
    edition = {1: "usa", 2: "jpn", 4: "eur"}.get(region, "region%x" % region)
# FNV-1a 64 of the whole file: the lifted code fits this XBE and no other,
# so main.c refuses another edition's disc instead of crashing in it.
h = 0xcbf29ce484222325
for b in raw:
    h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
with open(dst, "w", newline="\n") as f:   # LF on Windows too: the file is committed
    f.write("/* Generated by tools/first_lift.sh from the retail default.xbe. */\n")
    f.write("#pragma once\n\n")
    f.write("#define MC3_XBE_ENTRY_POINT %su\n" % d["entry_point"])
    f.write("#define MC3_XBE_TITLE_ID    %su\n" % d["title_id"])
    f.write("#define MC3_XBE_TITLE_NAME  \"%s\"\n" % d["title"].replace('"', ''))
    f.write("\n/* The disc this lift fits: checked at boot (src/main.c). */\n")
    f.write("#define MC3_XBE_SIZE        %du\n" % len(raw))
    f.write("#define MC3_XBE_FNV64       0x%016xull\n" % h)
    f.write("#define MC3_XBE_REGION      0x%xu\n" % region)
    f.write("#define MC3_XBE_VERSION     0x%xu\n" % version)
    f.write("#define MC3_EDITION         \"%s\"\n" % edition)
print("wrote %s (entry %s, title %s, %s)" % (dst, d["entry_point"], d["title_id"], d["type"]))
print("\n== Sections (XDK library ones like DSOUND/XPP are MC3_MMIO_SECTIONS candidates)")
for sec in d["sections"]:
    print("  %-10s %s %9d %s" % (sec["name"], sec["virtual_addr"], sec["virtual_size"],
                                 "code" if sec["executable"] else ""))
print("\n== XDK libraries (XDK %s)" % d["xdk_version"])
print("  " + ", ".join("%s %s" % (l["name"], l.get("build", "")) for l in d.get("libraries", [])))
EOF

echo
echo "== Lifting (this takes a while)"
"$MC3_REPO/tools/regen.sh"
