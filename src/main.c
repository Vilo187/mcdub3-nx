static void *load_file(const char *path, size_t *out_size)
{
    FILE *f = fopen(path, "rb");
    long size;
    void *data;

    if (!f)
        return NULL;
    fseek(f, 0, SEEK_END);
    size = ftell(f);
    fseek(f, 0, SEEK_SET);
    data = size > 0 ? malloc((size_t)size) : NULL;
    if (data && fread(data, 1, (size_t)size, f) != (size_t)size) {
        free(data);
        data = NULL;
    }
    fclose(f);
    if (data)
        *out_size = (size_t)size;
    return data;
}

static void fatal(const char *msg)
{
    fprintf(stderr, "[FATAL] %s\n", msg);
#ifdef __SWITCH__
    switch_error_dialog(msg);
#endif
}

static uint32_t apu_mmio_rd(void *opaque, uint32_t off, unsigned size)
{
    return (uint32_t)mcpx_apu_mmio_read((MCPXAPUState *)opaque, off, size);
}

static void apu_mmio_wr(void *opaque, uint32_t off, uint32_t val, unsigned size)
{
    mcpx_apu_mmio_write((MCPXAPUState *)opaque, off, val, size);
}

/* Runtime defaults: NFSU2's working set, the starting point for any XDK title
 * that draws through the NV2A pushbuffer and drives DirectSound and the pads
 * itself. Anything set in the environment (or mcdub3_env.txt) wins. Revisit
 * each once MC3 boots. */
static void set_runtime_defaults(void)
{
    setenv("RECOMP_VBLANK", "1", 0);           /* D3D waits on its vblank ISR */
    setenv("RECOMP_AC97_READY", "plain", 0);   /* DirectSound sees the codec */
    setenv("RECOMP_USB", "1", 0);              /* pads on the MCPX's OHCI */
    setenv("RECOMP_PB_EXEC", "1", 0);          /* execute the NV2A pushbuffer */
#ifdef __SWITCH__
    setenv("RECOMP_QUIET", "1", 0);            /* every log line costs an SD write */
#endif
}

static int game_main(void)
{
    char xbe_path[512];
    const char *game_dir;
    void *xbe_data;
    size_t xbe_size = 0;

    xbox_guest_pin(0);      /* the boot thread becomes the title's first thread */
#ifndef __SWITCH__
    /* Unbuffered on a PC; the Switch log keeps switch_nx.c's buffering,
     * where every unbuffered write would be an SD-card write. */
    setvbuf(stdout, NULL, _IONBF, 0);
    setvbuf(stderr, NULL, _IONBF, 0);
#endif
    printf("=== " MC3_XBE_TITLE_NAME " (Xbox) - static recompilation ===\n");
    install_crash_reporter();
    set_runtime_defaults();

    game_dir = getenv("MC3_GAME_DIR");
    if (!game_dir || !game_dir[0])
        game_dir = MC3_DEFAULT_GAME_DIR;
    snprintf(xbe_path, sizeof(xbe_path), "%s/default.xbe", game_dir);

    xbe_data = load_file(xbe_path, &xbe_size);
    if (!xbe_data) {
        fprintf(stderr, "cannot read %s\n", xbe_path);
        fatal("Failed to load default.xbe. Put the extracted disc in the game "
              "directory (or set MC3_GAME_DIR).");
        return 1;
    }
    printf("XBE %s: %zu bytes\n", xbe_path, xbe_size);

    if (!xbox_MemoryLayoutInit(xbe_data, xbe_size)) {
        fatal("Failed to initialise the Xbox memory layout "
              "(the guest address range may be unavailable).");
        free(xbe_data);
        return 1;
    }
    g_xbox_mem_offset = xbox_GetMemoryOffset();
    printf("Xbox memory mapped at host offset 0x%llX\n",
           (unsigned long long)g_xbox_mem_offset);

    /* The emulated APU. With RECOMP_AC97_READY=plain its registers stay plain
     * memory and the code lifted with --mmio-sections reaches it through the
     * MMIO accessors: no fault trapping, the same on every host. MC3_APU=0
     * runs without it (DirectSound creates, nothing plays). */
    if (getenv("RECOMP_AC97_READY") && !env_is("MC3_APU", "0")) {
        g_apu_state = mcpx_apu_init_standalone((uint8_t *)xbox_GetMemoryBase());
        fprintf(stderr, "[BOOT] emulated APU %s\n",
                g_apu_state ? "up" : "FAILED to initialise");
        if (g_apu_state && env_is("RECOMP_AC97_READY", "plain"))
            xbox_MmioRegister(APU_BASE, APU_END, apu_mmio_rd, apu_mmio_wr, g_apu_state);
    }

    /* The USB host controllers the title's XPP library drives to find pads. */
    xbox_OhciInit();

#ifndef _WIN32
    /* GPU renderer for the pushbuffer executor; MC3_GPU=0 keeps the
     * executor's CPU renderer (slow, but a useful reference). */
    if (!env_is("MC3_GPU", "0")) {
#  if defined(MC3_VULKAN)
        extern void nv2a_vk_install(void);
        nv2a_vk_install();
#  else
        extern void nv2a_gl_install(void);
        nv2a_gl_install();
#  endif
    }
#endif

    xbox_kernel_init();
    {
        /* Where the Xbox paths land (xboxrecomp kernel_path.c):
         *   \Device\CdRom0\, D:\ and Harddisk0\Partition1\ -> game_dir
         *     (so MC3's TDATA/UDATA settings and saves end up in game/)
         *   T:\ U:\ Z:\ and the raw partition images        -> save_dir
         * MC3_SAVE_DIR (tools/run_linux.sh: work/save) keeps the latter in
         * the repo instead of ~/.local/share; mcdub3_env.txt can set either
         * on the Switch, where the defaults are sdmc:/switch/mcdub3/{game,save}. */
        const char *save_dir = getenv("MC3_SAVE_DIR");
        xbox_path_init(game_dir, save_dir && save_dir[0] ? save_dir : MC3_DEFAULT_SAVE_DIR);
    }
    xbox_kernel_bridge_init();

    g_esp = XBOX_STACK_TOP;

    if (!recomp_dispatch_init())
        fprintf(stderr, "[BOOT] flat dispatch unavailable; "
                        "indirect calls will use the binary search\n");

    xbox_WatchdogStart();   /* inert unless RECOMP_WATCHDOG_SECS is set */

    printf("Starting guest at 0x%08X (esp=0x%08X)\n", MC3_XBE_ENTRY_POINT, g_esp);
    xbox_gil_mark_main();   /* the frame-rate thread (RECOMP_GIL_EAGER) */
    xbox_gil_enter();       /* one guest thread runs lifted code at a time */
    xbe_entry_point();
    xbox_gil_leave();

    printf("Guest returned. Cleaning up.\n");
    xbox_kernel_shutdown();
    xbox_MemoryLayoutShutdown();
    free(xbe_data);
    return 0;
}

#ifdef __SWITCH__
#include <pthread.h>

void xbox_nx_spread_thread(void);
void xbox_nx_track_thread(void *entry);

/* Horizon's main-thread stack is small for recompiled code: boot the title on
 * a thread with a desktop-sized stack, spread off core 0. */
static void *game_thread(void *arg)
{
    xbox_nx_spread_thread();
    xbox_nx_track_thread(NULL);
    *(int *)arg = game_main();
    return NULL;
}

int main(int argc, char **argv)
{
    pthread_attr_t attr;
    pthread_t th;
    int rc = 1;

    (void)argc;
    (void)argv;
    switch_boot();
    pthread_attr_init(&attr);
    pthread_attr_setstacksize(&attr, 16u * 1024 * 1024);
    if (pthread_create(&th, &attr, game_thread, &rc) == 0)
        pthread_join(th, NULL);
    else
        fprintf(stderr, "[FATAL] cannot start the game thread\n");
    switch_shutdown();
    return rc;
}
#else
int main(int argc, char **argv)
{
    (void)argc;
    (void)argv;
    return game_main();
}
#endif
