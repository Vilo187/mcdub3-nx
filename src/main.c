/* The MCPX APU's register window. */
#define APU_BASE 0xFE800000u
#define APU_END  0xFE880000u

static bool env_is(const char *name, const char *value)
{
    const char *v = getenv(name);
    return v && strcmp(v, value) == 0;
}

