#!/usr/bin/env python3
"""Generate failure-tracing wrappers for every function of some XBE sections.

    tools/trace_wrappers.py --sections XACTENG,DSOUND --out <file.c>
                            [--manual src/recomp_manual.c]

Each wrapper calls the lifted body (sub_X_gen) and, when it returns an
HRESULT failure, logs the function, its call depth on that thread and the
code. A failure travels up the call chain, so in the log the first line of a
burst is where it started and the lines after it are its callers.
Used by `make relift TRACE=XACTENG,DSOUND` (tools/regen.sh): the file lands
in work/ (it is derived from the game), is scanned with recomp_manual.c so
the lift emits the _gen bodies, and is compiled with the lifted code.

Functions recomp_manual.c already defines or wraps are left out. Output is
bounded: MC3_TRACE_MAX lines (default 400), at most 5 per function.
"""
import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "xboxrecomp"))
from tools.recomp.manual_scan import scan  # noqa: E402

HEADER = r'''/* Generated by tools/trace_wrappers.py -- do not edit; derived from the
 * game's function list, so it lives in work/ and is never committed.
 * Sections: @SECTIONS@ (@COUNT@ functions). */
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#include "recomp_types.h"

/* An HRESULT failure from a facility these libraries use: E_* (0x8000,
 * 0x8004), Win32 (0x8007), DirectSound (0x8878), XACT (0x8AC7). Contiguous-
 * memory pointers (0x80xxxxxx) collide only with the first 512 KB. */
static int trace_is_failure(uint32_t v)
{
    uint32_t f = v >> 16;
    return f == 0x8000u || f == 0x8004u || f == 0x8007u || f == 0x8878u || f == 0x8AC7u;
}

static __thread int s_depth;
static int s_max = -1;
static long s_lines;

static void trace_call(uint32_t addr, unsigned char *count, void (*fn)(void))
{
    uint32_t a0 = MEM32(g_esp + 4), a1 = MEM32(g_esp + 8), c = g_ecx;
    int depth = s_depth++;
    fn();
    s_depth--;
    if (s_max < 0) {
        const char *e = getenv("MC3_TRACE_MAX");
        s_max = e ? atoi(e) : 400;
    }
    if (trace_is_failure(g_eax) && *count < 5 && s_lines < s_max) {
        (*count)++;
        s_lines++;
        fprintf(stderr, "[TRACE] %*s%s sub_%08X (ecx %08X; %08X %08X) -> %08X\n",
                depth * 2, "", depth ? "<-" : "  ", addr, c, a0, a1, g_eax);
    }
}

'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sections", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--functions", required=True, help="disasm functions.json")
    ap.add_argument("--manual", default=os.path.join(HERE, "..", "src", "recomp_manual.c"))
    args = ap.parse_args()

    sections = [s.strip() for s in args.sections.split(",") if s.strip()]
    skip, wrap = scan(args.manual)[:2]
    taken = set(skip) | set(wrap)
    every = {int(f["start"], 16) for f in json.load(open(args.functions))
             if f.get("section") in sections}
    funcs = sorted(every - taken)
    if not funcs:
        sys.exit(f"no functions in {sections}")

    out = [HEADER.replace("@SECTIONS@", ", ".join(sections)).replace("@COUNT@", str(len(funcs)))]
    # One counter per function; written out, not by macro, so manual_scan
    # sees every wrapper.
    out.append(f"static unsigned char s_count[{len(funcs)}];\n\n")
    for i, a in enumerate(funcs):
        out.append(f"extern void sub_{a:08X}_gen(void);\n"
                   f"void sub_{a:08X}(void) {{ trace_call(0x{a:08X}u, &s_count[{i}], sub_{a:08X}_gen); }}\n")
    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        f.writelines(out)
    print(f"trace wrappers: {len(funcs)} functions in {', '.join(sections)} -> {args.out}"
          f" ({len(every & taken)} already handled by recomp_manual.c)")


if __name__ == "__main__":
    main()
